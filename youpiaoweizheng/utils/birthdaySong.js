//   **加歌只改 SONGS，引擎不用动** —— 取模天然支持任意首数。
//
// 【歌名都是真的，但不联网也不生成】纯人工整理。写错一个名字，粉丝一眼就看出来，
//   所以宁可少收也不凑数；要扩充就照 img 的写法补一行。
// ============================================================

