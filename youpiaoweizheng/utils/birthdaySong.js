// utils/birthdaySong.js —— 生日歌单：把 366 天映射到某位歌手的一首歌
// ============================================================
// 【这是什么】给一个生日 + 一位歌手，翻出属于这一天的一首歌 +
//   两句「为什么是它」+ 一句贴这首歌的鼓励，给页面渲染成一张能发出去的图。
//
// 【三条约束，都是这类玩法活不活得下来的关键】
//   ① **必须确定性**：同一天 + 同一位歌手，永远同一首。随机一次很爽，但朋友之间一对就穿帮
//      （「我 9 月 15 号是《演员》，你怎么不是」），第二天再打开又换了一首，
//      玩法立刻从「这是我的」塌成「抽奖」。
//   ② **纯端上、零云函数、零成本**：整个引擎 = 三张常量表 + 一个查表函数。
//      一天一万人玩和一个人玩，成本完全一样；**加一位歌手也只是多一张表** ——
//      拉新玩法的命脉在零边际成本。
//   ③ **不做命理**：这是「把你的生日放进一张 366 天的歌单里」的索引，不是测算。
//      微信对星座 / 运势 / 占卜类内容审得紧；也不要去暗示歌手本人参与了什么。
//
// 【映射规则】月份 → 12 个情绪格（只有季节物候句，**全歌手共用**：季节是日期带来的，
//   不是歌手带来的，换了歌手这句话不该跟着变）；日 → 格内取第几首（`day % 歌数`）。
//   **每个月放几首是自由的**（引擎天然支持任意首数），只要**每月至少 1 首、至多 3 首**即可 ——
//   每位歌手各排各的（2026-09-22 下午客户把目标定成「每位 36 首 = 每月 3 首」：
//   周杰伦 / 林俊杰 / 张学友 / 五月天满编 36 首；邓紫棋 27、谢霆锋 20 是「宁少勿滥」
//   砍下来的；薛之谦 15、陈奕迅 17 维持原样不硬凑 —— **八位合计 223 首**），
//   tests/birthday_song.test.js 会把关。
//
// 【选歌口径（2026-09-22 客户定的）：宁少勿滥，只要路人认得出的】
//   三条要同时成立：
//   ① **演唱会上会唱的** —— 巡演常驻曲、全场大合唱、返场压轴（客户当天点名要的口径）；
//   ② **不听这位歌手的人也听过** —— 街头店铺在放、KTV 有人点、上过热歌榜、
//      是影视综艺主题曲。只有粉丝叫得出的曲子一律不收 —— 玩法靠转发活着，
//      点开的人认不出歌名，这张图就没有发出去的理由；
//   ③ 见下方「只收本人演唱发行的独唱」。
//   所以 2026-09-22 清理过三轮：先由 3 首/月压到 2 首/月，再把薛之谦（-10 首）与陈奕迅（-7 首）
//   里剩下的冷门歌一并清掉，下午客户又改口要「加歌手、重点是演唱会上的歌」，
//   最终定成 36 首/人的目标 —— **宁可有些月份只有一两首（那个月出生的人翻出来是同一首），
//   也不填一首挡路的**。
//   口径③：只收**这位歌手自己演唱发行的独唱**——
//   合唱（薛之谦《纸船》是和郁可唯、陈奕迅《因为爱情》是和王菲）、
//   翻唱他人原唱（林俊杰《当你》原唱王心凌、《记得》原唱张惠妹、
//   薛之谦《哑巴》原唱刘维）、以及他只是词曲作者、由别人首唱的歌
//   （周杰伦《蜗牛》《世界末日》是写给别人的）—— 统统不收。
//   另有一类虽然确实是他首唱发行的，但大众会认成别人的作品（陈奕迅《淘汰》
//   是周杰伦词曲），也一并避开 —— 玩法吃的就是「哦这首我知道」，认错人就白搭。
//   还有一条：**同一首曲子的两个语言版本只留一首**。陈奕迅《十年》/《明年今日》、
//   《富士山下》/《爱情转移》各自同曲，旋律一模一样 —— 两首都收，粉丝一听就出戏，
//   还白占两个位置（保留哪一首见下方歌单里的注释）。
//   一个方向例外：**改编自日文歌的照收**（张学友《一路上有你》《李香兰》《每天爱你多一些》
//   《遥远的她》《蓝雨》《太阳星辰》《月半弯》《只想一生跟你走》都是翻的日本曲）。
//   口径③要避开的是「华语同行的原唱」（《当你》原唱王心凌那类），而这几首在华语听众的
//   认知里本来就是他的歌，还都是演唱会的大合唱曲 —— 按「点开的人认不认得」这唯一一把尺子，
//   它们该留。
//
// 【歌名全部逐首联网核过（2026-09-22）】来源为专辑曲目资料交叉比对
//   （维基专辑条目 / 百度百科 / Discogs / 音乐平台页 / 发行新闻）。
//   写错一个名字，粉丝一眼就看出来，所以宁可少收也不凑数。
//
// 【加一位歌手 = 在 ARTISTS 里加一项】页面的歌手切换、分享、海报一个字都不用改。
//   每首歌三个字段：`t` 歌名、`img` 这首歌写的是什么（当「为什么是它」）、
//   `cheer` 一句贴这首歌的鼓励。
// ============================================================

