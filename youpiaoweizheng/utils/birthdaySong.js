/** 默认歌手 = 第一位。分享链接没带歌手名、或名字已过期时用它 */
const DEFAULT_ARTIST = ARTISTS[0].name;

/** 找不到就回到第一位：分享链接里的歌手名可能过期或被改过，不该让页面白屏 */
function find(name) {
  for (let i = 0; i < ARTISTS.length; i++) {
    if (ARTISTS[i].name === name) return ARTISTS[i];
  }
  return ARTISTS[0];
}

/** 页面上的歌手切换用它渲染（顺序 = ARTISTS 的顺序） */
function names() {
  return ARTISTS.map((a) => a.name);
}

/** 这位歌手的歌单总首数（页面文案用它，别在别处写死数字） */
function total(name) {
  return find(name).songs.reduce((n, list) => n + list.length, 0);
}

/**
 * 翻出属于这一天的那首歌。
 * @param {number|string} month 1~12
 * @param {number|string} day   1~当月天数
 * @param {string} [artist]     歌手名，省略 = 默认歌手
 * @returns {object|null} 月/日非法返回 null（调用方自己决定怎么提示）
 */
function match(month, day, artist) {
  const m = parseInt(month, 10);
  const d = parseInt(day, 10);
  if (!(m >= 1 && m <= 12)) return null;
  if (!(d >= 1 && d <= DAYS[m - 1])) return null;

  const who = find(artist);
  const month0 = MONTHS[m - 1];
  const list = who.songs[m - 1];
  const song = list[d % list.length]; // 取模：同一天永远同一首，加歌也不用改这里

  return {
    m: m,
    d: d,
    artist: who.name,
    label: month0.label,
    scene: month0.scene,
    song: song,
    reasonA: '你生在' + month0.label + '（' + m + ' 月）—— ' + month0.scene + '。',
    reasonB: '属于这一天的是《' + song.t + '》：' + song.img + '。',
    cheer: song.cheer
  };
}

module.exports = { match, names, total, ARTISTS, MONTHS, DAYS, DEFAULT_ARTIST };
