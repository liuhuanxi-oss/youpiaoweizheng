/** 每月天数（2 月按 29 算：生日是「哪个月哪一天」，与具体年份无关） */
const DAYS = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

const ARTIST = '薛之谦';

/** 歌单总首数（页面文案用它，别在别处写死数字） */
function total() {
  return SONGS.reduce((n, list) => n + list.length, 0);
}

/**
 * 翻出属于这一天的那首歌。
 * @param {number|string} month 1~12
 * @param {number|string} day   1~当月天数
 * @returns {object|null} 月份非法返回 null（调用方自己决定怎么提示）
 */
function match(month, day) {
  const m = parseInt(month, 10);
  const d = parseInt(day, 10);
  if (!(m >= 1 && m <= 12)) return null;
  if (!(d >= 1 && d <= DAYS[m - 1])) return null;

  const month0 = MONTHS[m - 1];
  const list = SONGS[m - 1];
  const song = list[d % list.length]; // 取模：同一天永远同一首，加歌也不用改这里

  return {
    m: m,
    d: d,
    label: month0.label,
    scene: month0.scene,
    cheer: month0.cheer,
    song: song,
    reasonA: '你生在' + month0.label + '（' + m + ' 月）—— ' + month0.scene + '。',
    reasonB: '属于这一天的是《' + song.t + '》：' + song.img + '。'
  };
}

module.exports = { match, total, ARTIST, MONTHS, SONGS, DAYS };
