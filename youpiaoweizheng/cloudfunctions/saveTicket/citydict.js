// —— 索引构建（模块加载时一次） ——
const BY_NAME = {};   // 归一名 → {lat,lng}
const BY_PY = {};     // 拼音 → {lat,lng}
CITIES.forEach(([name, lat, lng, py]) => {
  const v = { lat, lng };
  if (!BY_NAME[name]) BY_NAME[name] = v; // 重复条目（洛阳/金华补位）首条生效
  if (!BY_PY[py]) BY_PY[py] = v;
});

/** 常用别名 → 标准名（先归一再查别名） */
const ALIAS = {
  '帝都': '北京', '魔都': '上海', '京城': '北京', '沪': '上海', '京': '北京',
  '杭城': '杭州', '蓉城': '成都', '江城': '武汉', '羊城': '广州', '鹏城': '深圳',
  '山城': '重庆', '冰城': '哈尔滨', '春城': '昆明', '星城': '长沙', '古都': '西安'
};

/** 归一化：去空格/中点，剥省市区等行政后缀 */
function norm(s) {
  return String(s || '')
    .replace(/[\s·・　]/g, '')
    .replace(/(特别行政区|维吾尔自治区|回族自治区|壮族自治区|自治区|自治州|省|市|地区|盟|县)$/g, '')
    .toLowerCase();
}

/**
 * 城市名 → 坐标 {lat, lng}（GCJ-02）；查不到返回 null（诚实降级，不阻塞调用方）
 * 匹配顺序：精确名 → 别名 → 拼音 → 包含匹配（处理「湖北省武汉」这类带省前缀的输入）
 */
function lookupCity(cityName) {
  const n = norm(cityName);
  if (!n) return null;
  if (BY_NAME[n]) return BY_NAME[n];
  if (ALIAS[n] && BY_NAME[ALIAS[n]]) return BY_NAME[ALIAS[n]];
  if (BY_PY[n]) return BY_PY[n];
  // 包含匹配：长输入含城市名（如「湖北省武汉」）；从长 key 到短 key 防误配
  const keys = Object.keys(BY_NAME).sort((a, b) => b.length - a.length);
  for (const k of keys) {
    if (n.length > k.length && n.includes(k)) return BY_NAME[k];
  }
  return null;
}

